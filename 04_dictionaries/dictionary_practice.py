# Dictionary Practice
# Topic: Storing and accessing information


# Creating a dictionary

student = {
    "name": "Bern",
    "age": 20,
    "course": "Computer Science"
}


# Accessing values

print(student["name"])
print(student["course"])


# Adding new information

student["year"] = 1

print(student)


# Changing information

student["age"] = 21

print(student)
